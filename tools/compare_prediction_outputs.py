r"""
Compare two folders of regenerated outputs
==========================================
Used to check that the table, figure and decision programs of the prediction
study reproduce the stored outputs.  Every file of FRESH is compared with the
file of the same relative path in REFERENCE:

  .csv, .json, .md, .tex   identical after line endings are made equal (CR LF
                           and LF are the same) and after the one-line note
                           ``<!-- Generated by ... -->`` of the Markdown tables
                           is left out.  The ``created`` and ``root`` fields of
                           a JSON file are left out.  Some JSON files hold the
                           SHA-256 of a file written earlier; it equals the
                           stored one only if the line endings of that file are
                           those of the stored run (CR LF on Windows).
  .png                     identical pixel arrays.  A difference is listed as
                           ``PNG DIFFERS`` and fails the check only with
                           ``--strict-png``: the size of a figure can change by a
                           few pixels with the version of matplotlib or the fonts
                           of the computer, while the tables are exact.
  .pdf                     not compared (the file holds its creation time)

The program prints one line per file that is not identical and a summary, and
exits with 1 if any file differs.  Files of FRESH that have no counterpart are
only counted.

    python tools/compare_prediction_outputs.py FRESH REFERENCE [--rename OLD=NEW]
"""
import argparse
import json
import sys
from pathlib import Path


def text_of(path: Path, renames=()) -> str:
    t = path.read_bytes().decode('utf-8').replace('\r\n', '\n')
    for old, new in renames:
        t = t.replace(old, new)
    if path.suffix == '.json':
        d = json.loads(t)
        if isinstance(d, dict):
            d.pop('created', None)
            d.pop('root', None)
        return json.dumps(d, indent=2, sort_keys=True)
    return '\n'.join(ln for ln in t.split('\n') if not ln.startswith('<!-- Generated by '))


def same_png(a: Path, b: Path) -> bool:
    import numpy as np
    from matplotlib import image
    x, y = image.imread(str(a)), image.imread(str(b))
    return x.shape == y.shape and bool(np.array_equal(x, y))


def main() -> int:
    ap = argparse.ArgumentParser(description='Compare regenerated outputs with stored ones')
    ap.add_argument('fresh')
    ap.add_argument('reference')
    ap.add_argument('--strict-png', action='store_true', help='a differing PNG file fails the check')
    ap.add_argument('--rename', action='append', default=[], metavar='OLD=NEW',
                    help='text of REFERENCE that was renamed since it was written; '
                         'OLD is replaced by NEW before comparing (may be repeated)')
    a = ap.parse_args()
    renames = [tuple(r.split('=', 1)) for r in a.rename]
    fresh, ref = Path(a.fresh), Path(a.reference)
    n = dict(identical=0, different=0, png=0, new=0, skipped=0)
    for f in sorted(p for p in fresh.rglob('*') if p.is_file()):
        rel = f.relative_to(fresh)
        g = ref / rel
        if not g.exists():
            n['new'] += 1
            continue
        ext = f.suffix.lower()
        if ext == '.pdf':
            n['skipped'] += 1
            continue
        if ext == '.png':
            if same_png(f, g):
                n['identical'] += 1
            else:
                n['png'] += 1
                print(f'PNG DIFFERS  {rel.as_posix()}')
            continue
        elif ext in ('.csv', '.json', '.md', '.tex'):
            ok = text_of(f) == text_of(g, renames)
        else:
            n['skipped'] += 1
            continue
        if ok:
            n['identical'] += 1
        else:
            n['different'] += 1
            print(f'DIFFERENT  {rel.as_posix()}')
    print(f"identical {n['identical']}, different {n['different']}, PNG differs {n['png']}, "
          f"without counterpart {n['new']}, not compared {n['skipped']}")
    failed = n['different'] > 0 or (a.strict_png and n['png'] > 0)
    print('COMPARE FAILED' if failed else 'COMPARE OK')
    return 1 if failed else 0


if __name__ == '__main__':
    sys.exit(main())
