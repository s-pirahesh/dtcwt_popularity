r"""
Unit checks for tools/compare_prediction_outputs.py
===================================================
Builds small folders in a temporary directory and checks that the comparison

  1. passes on identical files and ignores the line endings,
  2. ignores the ``<!-- Generated by ... -->`` line of a Markdown table,
  3. ignores the ``created`` and ``root`` fields of a JSON file,
  4. fails on one changed digit in a CSV file, in a table and in a JSON value,
  5. applies ``--rename`` to the reference text only,
  6. counts files without a counterpart and does not compare PDF files,
  7. reports a differing PNG file and fails on it only with ``--strict-png``.

    python tools/test_compare_prediction_outputs.py
"""
import json
import subprocess
import sys
import tempfile
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
TOOL = ROOT / 'tools' / 'compare_prediction_outputs.py'
FAILED = []


def check(name, cond):
    print(('ok     ' if cond else 'FAILED ') + name)
    if not cond:
        FAILED.append(name)


def run(fresh, ref, *extra):
    r = subprocess.run([sys.executable, str(TOOL), str(fresh), str(ref), *extra],
                       capture_output=True, text=True)
    return r.returncode, r.stdout


def put(folder, name, text, newline='\n'):
    p = Path(folder) / name
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_bytes(text.replace('\n', newline).encode('utf-8'))


def png(folder, name, value):
    import matplotlib
    matplotlib.use('Agg')
    from matplotlib import image
    p = Path(folder) / name
    p.parent.mkdir(parents=True, exist_ok=True)
    image.imsave(str(p), np.full((4, 5, 3), value, dtype=float))


def main():
    with tempfile.TemporaryDirectory() as td:
        td = Path(td)
        fresh, ref = td / 'fresh', td / 'ref'
        tab = '<!-- Generated by tools/x.py from a.csv. -->\n\n| a | b |\n|--|--|\n| 1 | 2 |\n'
        put(fresh, 'tab.md', tab)
        put(ref, 'tab.md', tab.replace('tools/x.py', 'other/y.py'), '\r\n')
        put(fresh, 'd.csv', 'a,b\n1,0.25\n')
        put(ref, 'd.csv', 'a,b\n1,0.25\n', '\r\n')
        put(fresh, 'm.json', json.dumps({'created': '2026-01-01', 'root': 'A', 'v': [1, 2]}))
        put(ref, 'm.json', json.dumps({'created': '2020-05-05', 'root': 'B', 'v': [1, 2]}))
        put(fresh, 'only_fresh.csv', 'x\n1\n')
        put(fresh, 'f.pdf', 'one')
        put(ref, 'f.pdf', 'two')
        code, out = run(fresh, ref)
        check('identical files, line endings, note line and created/root are ignored',
              code == 0 and 'identical 3' in out and 'different 0' in out)
        check('file without counterpart and PDF are not compared',
              'without counterpart 1' in out and 'not compared 1' in out)

        put(fresh, 'd.csv', 'a,b\n1,0.26\n')
        code, out = run(fresh, ref)
        check('one changed digit in a CSV file fails', code == 1 and 'DIFFERENT  d.csv' in out)
        put(fresh, 'd.csv', 'a,b\n1,0.25\n')
        put(fresh, 'tab.md', tab.replace('| 1 | 2 |', '| 1 | 3 |'))
        code, out = run(fresh, ref)
        check('one changed digit in a table fails', code == 1 and 'DIFFERENT  tab.md' in out)
        put(fresh, 'tab.md', tab)
        put(fresh, 'm.json', json.dumps({'created': '2026-01-01', 'root': 'A', 'v': [1, 3]}))
        code, out = run(fresh, ref)
        check('one changed value in a JSON file fails', code == 1 and 'DIFFERENT  m.json' in out)
        put(fresh, 'm.json', json.dumps({'created': '2026-01-01', 'root': 'A', 'v': [1, 2]}))

        put(ref, 'tab.md', tab.replace('1 | 2', 'old_name | 2'))
        code, out = run(fresh, ref)
        check('a renamed text fails without --rename', code == 1)
        put(fresh, 'tab.md', tab.replace('| 1 | 2 |', '| new_name | 2 |'))
        code, out = run(fresh, ref, '--rename', 'old_name=new_name')
        check('--rename is applied to the reference text', code == 0 and 'different 0' in out)

        put(fresh, 'tab.md', tab)
        put(ref, 'tab.md', tab)
        png(fresh, 'p.png', 0.2)
        png(ref, 'p.png', 0.2)
        code, out = run(fresh, ref)
        check('identical PNG files pass', code == 0 and 'PNG differs 0' in out)
        png(fresh, 'p.png', 0.9)
        code, out = run(fresh, ref)
        check('a differing PNG file is reported and does not fail', code == 0 and 'PNG DIFFERS  p.png' in out)
        code, out = run(fresh, ref, '--strict-png')
        check('a differing PNG file fails with --strict-png', code == 1)
    if FAILED:
        print('FAILED: ' + ', '.join(FAILED))
        return 1
    print('ALL OK')
    return 0


if __name__ == '__main__':
    sys.exit(main())
